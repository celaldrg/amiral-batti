/**
 * @param {unknown} value A saved or requested language.
 * @returns {'en'|'tr'} The language itself when supported, otherwise English.
 */
export function normalizeLanguage(value) {
  return LANGUAGES.includes(value) ? value : LANGUAGES[0];
}

/**
 * Looks up a string and fills in its parameters. Missing keys fall back to
 * English, then to the key itself; unknown parameters stay as written.
 * @param {string} lang
 * @param {string} key
 * @param {Record<string, string|number>} [params]
 * @returns {string}
 */
export function translate(lang, key, params = {}) {
  const table = STRINGS[normalizeLanguage(lang)];
  const singular = params.count === 1 ? table[`${key}_one`] : undefined;
  const template = singular ?? table[key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (
    Object.hasOwn(params, name) ? String(params[name]) : match
  ));
}
